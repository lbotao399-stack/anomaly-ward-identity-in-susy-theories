def bubble_routes() -> list[Route]:
    """I_[1] V_[1]: one bridge u at the source and one cubic action vertex."""

    routes: list[Route] = []
    source_words = {
        "I1_bridge_left": ("u[A0]", "u[BL]", "phi1[B0]"),
        "I1_bridge_right": ("u[A0]", "u[BR]", "phi1[B0]"),
    }
    for source_name, source in source_words.items():
        for action_name, action in CUBIC_VERTICES.items():
            for source_internal in itertools.combinations(range(3), 2):
                source_external = next(index for index in range(3) if index not in source_internal)
                source_pair = tuple(source[index] for index in source_internal)
                for action_internal in itertools.combinations(range(3), 2):
                    action_external = next(index for index in range(3) if index not in action_internal)
                    action_pair = tuple(action[index] for index in action_internal)
                    for matching in all_bijections(source_pair, action_pair):
                        edges = tuple(
                            (source_pair[left], action_pair[right]) for left, right in matching
                        )
                        routes.append(
                            Route(
                                sector="I1_V1_BUBBLE",
                                source_word=source_name,
                                action_word=action_name,
                                internal_edges=edges,
                                external_fields=(bare(source[source_external]), bare(action[action_external])),
                            )
                        )
    return routes


def seagull_routes() -> list[Route]:
    """I_[0] V_[2]: the two source ports enter one quartic action vertex."""

    routes: list[Route] = []
    source = ("u[A0]", "phi1[B0]")
    for action_name, action in QUARTIC_VERTICES.items():
        for action_internal in itertools.combinations(range(4), 2):
            action_pair = tuple(action[index] for index in action_internal)
            for matching in all_bijections(source, action_pair):
                external = tuple(
                    bare(action[index]) for index in range(4) if index not in action_internal
                )
                edges = tuple((source[left], action_pair[right]) for left, right in matching)
                routes.append(
                    Route(
                        sector="I0_V2_SEAGULL",
                        source_word="I0",
                        action_word=action_name,
                        internal_edges=edges,
                        external_fields=(external[0], external[1]),
                    )
                )
    return routes


def tadpole_routes() -> list[Route]:
    """I_[2]: contract one compatible pair inside the order-two source."""

    routes: list[Route] = []
    source_words = {
        "I2_bridge_left_squared": ("u[A0]", "u[BL0]", "u[BL1]", "phi1[B0]"),
        "I2_bridge_crossed": ("u[A0]", "u[BL]", "u[BR]", "phi1[B0]"),
        "I2_bridge_right_squared": ("u[A0]", "u[BR0]", "u[BR1]", "phi1[B0]"),
    }
    for source_name, source in source_words.items():
        for left, right in itertools.combinations(range(4), 2):
            if not compatible(source[left], source[right]):
                continue
            external = tuple(bare(source[index]) for index in range(4) if index not in (left, right))
            routes.append(
                Route(
                    sector="I2_TADPOLE",
                    source_word=source_name,
                    action_word="NONE",
                    internal_edges=((source[left], source[right]),),
                    external_fields=(external[0], external[1]),
                )
            )
    return routes


def triangle_routes() -> list[Route]:
    """I_[0] V_[1] V_[1], retained only as the support-control family."""

    routes: list[Route] = []
    source = ("u[A0]", "phi1[B0]")
    for left_name, left in CUBIC_VERTICES.items():
        for right_name, right in CUBIC_VERTICES.items():
            for left_source in range(3):
                if not compatible(source[0], left[left_source]):
                    continue
                for right_source in range(3):
                    if not compatible(source[1], right[right_source]):
                        continue
                    left_remaining = tuple(index for index in range(3) if index != left_source)
                    right_remaining = tuple(index for index in range(3) if index != right_source)
                    for left_bridge in left_remaining:
                        for right_bridge in right_remaining:
                            if not compatible(left[left_bridge], right[right_bridge]):
                                continue
                            left_external = next(index for index in left_remaining if index != left_bridge)
                            right_external = next(index for index in right_remaining if index != right_bridge)
                            routes.append(
                                Route(
                                    sector="I0_V1_V1_TRIANGLE",
                                    source_word="I0",
                                    action_word=f"{left_name}>{right_name}",
                                    internal_edges=(
                                        (source[0], left[left_source]),
                                        (left[left_bridge], right[right_bridge]),
                                        (source[1], right[right_source]),
                                    ),
                                    external_fields=(bare(left[left_external]), bare(right[right_external])),
                                )
                            )
    return routes


class Ledger:
    def __init__(self) -> None:
        self.rows: list[dict[str, object]] = []

    def check(self, check_id: str, actual: object, expected: object) -> None:
        passed = actual == expected

        def serializable(value: object) -> object:
            if isinstance(value, Fraction):
                return fraction_text(value)
            if isinstance(value, sp.Basic):
                return sp.sstr(sp.factor(value)).replace("I", "i")
            if isinstance(value, tuple):
                return [serializable(entry) for entry in value]
            if isinstance(value, list):
                return [serializable(entry) for entry in value]
            if isinstance(value, dict):
                return {str(key): serializable(entry) for key, entry in value.items()}
            return value

        self.rows.append(
            {
                "id": check_id,
                "status": "PASS" if passed else "FAIL",
                "actual": serializable(actual),
                "expected": serializable(expected),
            }
        )
        if not passed:
            raise AssertionError(f"{check_id}: {actual!r} != {expected!r}")


