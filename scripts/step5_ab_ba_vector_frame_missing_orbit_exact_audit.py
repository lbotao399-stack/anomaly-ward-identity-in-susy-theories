def fraction_text(value: Fraction) -> str:
    return str(value.numerator) if value.denominator == 1 else f"{value.numerator}/{value.denominator}"


def convolve(left: tuple[Fraction, ...], right: tuple[Fraction, ...], order: int = 2) -> tuple[Fraction, ...]:
    return tuple(
        sum(
            (left[index] * right[degree - index] for index in range(degree + 1)
             if index < len(left) and degree - index < len(right)),
            Fraction(0),
        )
        for degree in range(order + 1)
    )


def bare(port: str) -> str:
    return port.split("[")[0]


def dual(field: str) -> str:
    field = bare(field)
    if field == "u":
        return "u"
    if field.startswith("phi"):
        return "tilde" + field
    if field.startswith("tildephi"):
        return field.removeprefix("tilde")
    raise ValueError(field)


def compatible(left: str, right: str) -> bool:
    return dual(left) == bare(right)


def all_bijections(left: tuple[str, ...], right: tuple[str, ...]) -> Iterable[tuple[tuple[int, int], ...]]:
    if len(left) != len(right):
        return ()
    rows: list[tuple[tuple[int, int], ...]] = []
    for permutation in itertools.permutations(range(len(right))):
        if all(compatible(left[index], right[permutation[index]]) for index in range(len(left))):
            rows.append(tuple((index, permutation[index]) for index in range(len(left))))
    return tuple(rows)


@dataclass(frozen=True)
class Route:
    sector: str
    source_word: str
    action_word: str
    internal_edges: tuple[tuple[str, str], ...]
    external_fields: tuple[str, str]

    @property
    def output_word(self) -> str:
        return ">".join(self.external_fields)


