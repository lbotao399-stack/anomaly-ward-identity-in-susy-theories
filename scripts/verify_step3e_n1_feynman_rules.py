def q(value: int | Fraction) -> QI:
    return QI(Fraction(value))


Exponent = tuple[int, int, int, int]


@dataclass(frozen=True)
class Poly:
    terms: tuple[tuple[Exponent, QI], ...] = ()

    @staticmethod
    def from_dict(data: dict[Exponent, QI]) -> "Poly":
        return Poly(tuple(sorted((power, value) for power, value in data.items() if value != ZERO)))

    @staticmethod
    def constant(value: QI) -> "Poly":
        return Poly.from_dict({(0, 0, 0, 0): value})

    @staticmethod
    def variable(index: int) -> "Poly":
        power = [0, 0, 0, 0]
        power[index] = 1
        return Poly.from_dict({tuple(power): ONE})

    def as_dict(self) -> dict[Exponent, QI]:
        return dict(self.terms)

    def __add__(self, other: "Poly") -> "Poly":
        data = self.as_dict()
        for power, value in other.terms:
            data[power] = data.get(power, ZERO) + value
        return Poly.from_dict(data)

    def __neg__(self) -> "Poly":
        return Poly.from_dict({power: -value for power, value in self.terms})

    def __sub__(self, other: "Poly") -> "Poly":
        return self + (-other)

    def __mul__(self, other: "Poly") -> "Poly":
        data: dict[Exponent, QI] = {}
        for left_power, left_value in self.terms:
            for right_power, right_value in other.terms:
                power = tuple(left_power[i] + right_power[i] for i in range(4))
                data[power] = data.get(power, ZERO) + left_value * right_value
        return Poly.from_dict(data)

    def scale(self, value: QI) -> "Poly":
        return Poly.from_dict({power: value * coefficient for power, coefficient in self.terms})

    def evaluate(self, values: tuple[QI, QI, QI, QI]) -> QI:
        result = ZERO
        for powers, coefficient in self.terms:
            term = coefficient
            for index, power in enumerate(powers):
                for _ in range(power):
                    term = term * values[index]
            result = result + term
        return result


PZERO = Poly()
PONE = Poly.constant(ONE)
DVAR = tuple(Poly.variable(index) for index in range(4))


def psum(values: Iterable[Poly]) -> Poly:
    result = PZERO
    for value in values:
        result = result + value
    return result


Matrix = list[list[Poly]]
QMatrix = list[list[QI]]
DIM = 16


def zero_matrix(rows: int = DIM, columns: int = DIM) -> Matrix:
    return [[PZERO for _ in range(columns)] for _ in range(rows)]


def identity_matrix(size: int = DIM) -> Matrix:
    result = zero_matrix(size, size)
    for index in range(size):
        result[index][index] = PONE
    return result


def matrix_add(left: Matrix, right: Matrix) -> Matrix:
    return [
        [left[row][column] + right[row][column] for column in range(len(left[0]))]
        for row in range(len(left))
    ]


def matrix_scale(value: QI | Poly, matrix: Matrix) -> Matrix:
    factor = value if isinstance(value, Poly) else Poly.constant(value)
    return [[factor * entry for entry in row] for row in matrix]


def matrix_multiply(left: Matrix, right: Matrix) -> Matrix:
    rows = len(left)
    middle = len(right)
    columns = len(right[0])
    result = zero_matrix(rows, columns)
    for row in range(rows):
        for pivot in range(middle):
            if not left[row][pivot].terms:
                continue
            for column in range(columns):
                if right[pivot][column].terms:
                    result[row][column] = (
                        result[row][column] + left[row][pivot] * right[pivot][column]
                    )
    return result


def matrix_sum(values: Iterable[Matrix]) -> Matrix:
    result = zero_matrix()
    for value in values:
        result = matrix_add(result, value)
    return result


def poly_block_matrix(a: Matrix, b: Matrix, c: Matrix, d: Matrix) -> Matrix:
    top = [a[row] + b[row] for row in range(len(a))]
    bottom = [c[row] + d[row] for row in range(len(c))]
    return top + bottom


def grassmann_multiplication(variable: int) -> Matrix:
    result = zero_matrix()
    for mask in range(DIM):
        if mask & (1 << variable):
            continue
        sign = -1 if sum((mask >> prior) & 1 for prior in range(variable)) % 2 else 1
        result[mask | (1 << variable)][mask] = Poly.constant(q(sign))
    return result


def grassmann_derivative(variable: int) -> Matrix:
    result = zero_matrix()
    for mask in range(DIM):
        if not mask & (1 << variable):
            continue
        sign = -1 if sum((mask >> prior) & 1 for prior in range(variable)) % 2 else 1
        result[mask ^ (1 << variable)][mask] = Poly.constant(q(sign))
    return result


