@dataclass(frozen=True, order=True)
class QI:
    real: Fraction = Fraction(0)
    imag: Fraction = Fraction(0)

    def __add__(self, other: "QI") -> "QI":
        return QI(self.real + other.real, self.imag + other.imag)

    def __neg__(self) -> "QI":
        return QI(-self.real, -self.imag)

    def __sub__(self, other: "QI") -> "QI":
        return self + (-other)

    def __mul__(self, other: "QI") -> "QI":
        return QI(
            self.real * other.real - self.imag * other.imag,
            self.real * other.imag + self.imag * other.real,
        )

    def inverse(self) -> "QI":
        norm = self.real * self.real + self.imag * self.imag
        if norm == 0:
            raise ZeroDivisionError("zero in Q(i)")
        return QI(self.real / norm, -self.imag / norm)

    def __truediv__(self, other: "QI") -> "QI":
        return self * other.inverse()

    def text(self) -> str:
        if self.imag == 0:
            return str(self.real)
        if self.real == 0:
            if self.imag == 1:
                return "i"
            if self.imag == -1:
                return "-i"
            return f"{self.imag}i"
        sign = "+" if self.imag > 0 else "-"
        magnitude = abs(self.imag)
        imag = "i" if magnitude == 1 else f"{magnitude}i"
        return f"{self.real}{sign}{imag}"


