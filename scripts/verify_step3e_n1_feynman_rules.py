def typed_graph_orbit_checks(recorder: Recorder) -> None:
    group = (0, 1)
    pairings = (
        ("direct-color-word", 0),
        ("direct-color-word", 1),
        ("crossed-color-word", 0),
        ("crossed-color-word", 1),
    )

    def act(group_element: int, pairing: tuple[str, int]) -> tuple[str, int]:
        decoration, copy_label = pairing
        return decoration, copy_label ^ group_element

    unseen = set(pairings)
    orbits: list[set[tuple[str, int]]] = []
    while unseen:
        representative = min(unseen)
        orbit = {act(element, representative) for element in group}
        orbits.append(orbit)
        unseen -= orbit
    orbits.sort(key=lambda orbit: min(orbit))
    recorder.check("typed graph orbit count", len(orbits), 2, "typed_graph")
    recorder.check(
        "typed graph orbit disjoint union",
        set().union(*orbits),
        set(pairings),
        "typed_graph",
    )
    recorder.check(
        "typed graph decorations preserved",
        all(act(element, pairing)[0] == pairing[0] for element in group for pairing in pairings),
        True,
        "typed_graph",
    )
    orbit_stabilizer_rows = []
    for orbit in orbits:
        representative = min(orbit)
        stabilizer = [
            element for element in group if act(element, representative) == representative
        ]
        orbit_stabilizer_rows.append(
            {
                "orbit_size": len(orbit),
                "group_over_stabilizer": Fraction(len(group), len(stabilizer)),
            }
        )
    recorder.check(
        "typed graph orbit-stabilizer rows",
        orbit_stabilizer_rows,
        [
            {"orbit_size": 2, "group_over_stabilizer": Fraction(2)},
            {"orbit_size": 2, "group_over_stabilizer": Fraction(2)},
        ],
        "typed_graph",
    )
    weights = {
        ("direct-color-word", 0): Fraction(2),
        ("direct-color-word", 1): Fraction(-1),
        ("crossed-color-word", 0): Fraction(3),
        ("crossed-color-word", 1): Fraction(5),
    }
    full_sum = sum((weights[pairing] for pairing in pairings), Fraction(0))
    orbit_sum = sum(
        (sum((weights[pairing] for pairing in orbit), Fraction(0)) for orbit in orbits),
        Fraction(0),
    )
    recorder.check(
        "typed graph weight sum by orbit decomposition",
        orbit_sum,
        full_sum,
        "typed_graph",
    )
    recorder.check(
        "typed graph no false single-orbit reduction",
        len(orbits) == 1,
        False,
        "typed_graph",
    )


