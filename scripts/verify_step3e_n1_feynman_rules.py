def schur_checks(recorder: Recorder) -> None:
    a = [[Fraction(3), Fraction(1)], [Fraction(1), Fraction(2)]]
    y = [[Fraction(2), Fraction(1)], [Fraction(1), Fraction(3)]]
    f = [[Fraction(1), Fraction(2)], [Fraction(0), Fraction(1)]]
    f_sharp = rtranspose(f)
    y_inverse = rinverse(y)
    schur = radd(a, rmul(rmul(f_sharp, y_inverse), f))
    schur_inverse = rinverse(schur)
    h = block_matrix(a, f_sharp, f, rneg(y))
    h_inverse = block_matrix(
        schur_inverse,
        rmul(rmul(schur_inverse, f_sharp), y_inverse),
        rmul(rmul(y_inverse, f), schur_inverse),
        radd(
            rneg(y_inverse),
            rmul(rmul(rmul(rmul(y_inverse, f), schur_inverse), f_sharp), y_inverse),
        ),
    )
    recorder.check("multiplier Schur inverse left composition", rmul(h, h_inverse), rid(4), "schur")
    recorder.check("multiplier Schur inverse right composition", rmul(h_inverse, h), rid(4), "schur")

    hdd = [[Fraction(4), Fraction(1)], [Fraction(2), Fraction(5)]]
    hda = [[Fraction(1), Fraction(2)], [Fraction(0), Fraction(1)]]
    had = [[Fraction(2), Fraction(0)], [Fraction(1), Fraction(1)]]
    haa = [[Fraction(3), Fraction(1)], [Fraction(1), Fraction(2)]]
    haa_inverse = rinverse(haa)
    reduced = radd(hdd, rneg(rmul(rmul(hda, haa_inverse), had)))
    full = block_matrix(hdd, hda, had, haa)
    left = block_matrix(rid(2), rneg(rmul(hda, haa_inverse)), rzero(2, 2), rid(2))
    right = block_matrix(rid(2), rzero(2, 2), rneg(rmul(haa_inverse, had)), rid(2))
    diagonalized = block_matrix(reduced, rzero(2, 2), rzero(2, 2), haa)
    recorder.check("auxiliary Schur block elimination identity", rmul(rmul(left, full), right), diagonalized, "schur")
    recorder.check(
        "auxiliary reduced Hessian",
        reduced,
        radd(hdd, rneg(rmul(rmul(hda, haa_inverse), had))),
        "schur",
    )

    generic_a = [[Fraction(5), Fraction(1)], [Fraction(2), Fraction(4)]]
    generic_b = [[Fraction(1)], [Fraction(2)]]
    generic_c = [[Fraction(3), Fraction(1)]]
    generic_d = [[Fraction(2)]]
    generic_d_inverse = rinverse(generic_d)
    generic_s = radd(
        generic_a,
        rneg(rmul(rmul(generic_b, generic_d_inverse), generic_c)),
    )
    generic_s_inverse = rinverse(generic_s)
    generic_h = block_matrix(generic_a, generic_b, generic_c, generic_d)
    generic_h_inverse = block_matrix(
        generic_s_inverse,
        rneg(rmul(rmul(generic_s_inverse, generic_b), generic_d_inverse)),
        rneg(rmul(rmul(generic_d_inverse, generic_c), generic_s_inverse)),
        radd(
            generic_d_inverse,
            rmul(
                rmul(
                    rmul(rmul(generic_d_inverse, generic_c), generic_s_inverse),
                    generic_b,
                ),
                generic_d_inverse,
            ),
        ),
    )
    recorder.check(
        "generic recursive Schur inverse left composition",
        rmul(generic_h, generic_h_inverse),
        rid(3),
        "schur",
    )
    recorder.check(
        "generic recursive Schur inverse right composition",
        rmul(generic_h_inverse, generic_h),
        rid(3),
        "schur",
    )


