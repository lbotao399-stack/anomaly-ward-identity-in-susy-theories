RMatrix = list[list[Fraction]]


def rzero(rows: int, columns: int) -> RMatrix:
    return [[Fraction(0) for _ in range(columns)] for _ in range(rows)]


def rid(size: int) -> RMatrix:
    result = rzero(size, size)
    for index in range(size):
        result[index][index] = Fraction(1)
    return result


def radd(left: RMatrix, right: RMatrix) -> RMatrix:
    return [[left[i][j] + right[i][j] for j in range(len(left[0]))] for i in range(len(left))]


def rneg(matrix: RMatrix) -> RMatrix:
    return [[-entry for entry in row] for row in matrix]


def rsub(left: RMatrix, right: RMatrix) -> RMatrix:
    return radd(left, rneg(right))


def rmul(left: RMatrix, right: RMatrix) -> RMatrix:
    return [
        [sum(left[i][k] * right[k][j] for k in range(len(right))) for j in range(len(right[0]))]
        for i in range(len(left))
    ]


def rtranspose(matrix: RMatrix) -> RMatrix:
    return [list(row) for row in zip(*matrix)]


def rdiag(values: Iterable[Fraction | int]) -> RMatrix:
    entries = [Fraction(value) for value in values]
    result = rzero(len(entries), len(entries))
    for index, value in enumerate(entries):
        result[index][index] = value
    return result


def rdirect_sum(*matrices: RMatrix) -> RMatrix:
    size = sum(len(matrix) for matrix in matrices)
    result = rzero(size, size)
    offset = 0
    for matrix in matrices:
        for row in range(len(matrix)):
            for column in range(len(matrix[0])):
                result[offset + row][offset + column] = matrix[row][column]
        offset += len(matrix)
    return result


def rinverse(matrix: RMatrix) -> RMatrix:
    size = len(matrix)
    augmented = [matrix[row][:] + rid(size)[row] for row in range(size)]
    for column in range(size):
        pivot = next(row for row in range(column, size) if augmented[row][column] != 0)
        augmented[column], augmented[pivot] = augmented[pivot], augmented[column]
        scale = augmented[column][column]
        augmented[column] = [entry / scale for entry in augmented[column]]
        for row in range(size):
            if row == column:
                continue
            factor = augmented[row][column]
            augmented[row] = [
                augmented[row][index] - factor * augmented[column][index]
                for index in range(2 * size)
            ]
    return [row[size:] for row in augmented]


def block_matrix(a: RMatrix, b: RMatrix, c: RMatrix, d: RMatrix) -> RMatrix:
    top = [a[row] + b[row] for row in range(len(a))]
    bottom = [c[row] + d[row] for row in range(len(c))]
    return top + bottom


def rdeterminant(matrix: RMatrix) -> Fraction:
    work = [row[:] for row in matrix]
    result = Fraction(1)
    for column in range(len(work)):
        pivot = next(
            (row for row in range(column, len(work)) if work[row][column] != 0),
            None,
        )
        if pivot is None:
            return Fraction(0)
        if pivot != column:
            work[column], work[pivot] = work[pivot], work[column]
            result = -result
        diagonal = work[column][column]
        result *= diagonal
        for row in range(column + 1, len(work)):
            factor = work[row][column] / diagonal
            for index in range(column, len(work)):
                work[row][index] -= factor * work[column][index]
    return result


def rtrace(matrix: RMatrix) -> Fraction:
    return sum((matrix[index][index] for index in range(len(matrix))), Fraction(0))


CMatrix = list[list[QI]]


def czero(rows: int, columns: int) -> CMatrix:
    return [[ZERO for _ in range(columns)] for _ in range(rows)]


def cid(size: int) -> CMatrix:
    result = czero(size, size)
    for index in range(size):
        result[index][index] = ONE
    return result


def cfrom_r(matrix: RMatrix) -> CMatrix:
    return [[q(entry) for entry in row] for row in matrix]


def cscale(value: QI, matrix: CMatrix) -> CMatrix:
    return [[value * entry for entry in row] for row in matrix]


def cadd(left: CMatrix, right: CMatrix) -> CMatrix:
    return [
        [left[row][column] + right[row][column] for column in range(len(left[0]))]
        for row in range(len(left))
    ]


def cneg(matrix: CMatrix) -> CMatrix:
    return cscale(MINUS_ONE, matrix)


def cmul(left: CMatrix, right: CMatrix) -> CMatrix:
    result = czero(len(left), len(right[0]))
    for row in range(len(left)):
        for pivot in range(len(right)):
            if left[row][pivot] == ZERO:
                continue
            for column in range(len(right[0])):
                result[row][column] = (
                    result[row][column] + left[row][pivot] * right[pivot][column]
                )
    return result


def ctranspose(matrix: CMatrix) -> CMatrix:
    return [list(row) for row in zip(*matrix)]


def cinverse(matrix: CMatrix) -> CMatrix:
    size = len(matrix)
    augmented = [matrix[row][:] + cid(size)[row] for row in range(size)]
    for column in range(size):
        pivot = next(row for row in range(column, size) if augmented[row][column] != ZERO)
        augmented[column], augmented[pivot] = augmented[pivot], augmented[column]
        scale = augmented[column][column]
        augmented[column] = [entry / scale for entry in augmented[column]]
        for row in range(size):
            if row == column:
                continue
            factor = augmented[row][column]
            augmented[row] = [
                augmented[row][index] - factor * augmented[column][index]
                for index in range(2 * size)
            ]
    return [row[size:] for row in augmented]


def ctensor(left: CMatrix, right: CMatrix) -> CMatrix:
    result = czero(len(left) * len(right), len(left[0]) * len(right[0]))
    for left_row in range(len(left)):
        for left_column in range(len(left[0])):
            for right_row in range(len(right)):
                for right_column in range(len(right[0])):
                    result[left_row * len(right) + right_row][
                        left_column * len(right[0]) + right_column
                    ] = left[left_row][left_column] * right[right_row][right_column]
    return result


def tensor_r_poly(left: RMatrix, right: Matrix) -> Matrix:
    result = zero_matrix(len(left) * len(right), len(left[0]) * len(right[0]))
    for left_row in range(len(left)):
        for left_column in range(len(left[0])):
            for right_row in range(len(right)):
                for right_column in range(len(right[0])):
                    result[left_row * len(right) + right_row][
                        left_column * len(right[0]) + right_column
                    ] = right[right_row][right_column].scale(q(left[left_row][left_column]))
    return result


def sigma_dot(
    matrices: tuple[tuple[tuple[QI, QI], tuple[QI, QI]], ...],
    derivative: tuple[QI, QI, QI, QI],
) -> CMatrix:
    result = czero(2, 2)
    for mu in range(4):
        for row in range(2):
            for column in range(2):
                result[row][column] = (
                    result[row][column] + derivative[mu] * matrices[mu][row][column]
                )
    return result


def nonsymmetric_chiral_checks(
    recorder: Recorder, operators: dict[str, SuperspaceOperators]
) -> None:
    z = [[Fraction(1), Fraction(2)], [Fraction(3), Fraction(5)]]
    z_inverse = rinverse(z)
    z_transpose = rtranspose(z)
    z_inverse_transpose = rtranspose(z_inverse)
    recorder.check("nonsymmetric Z witness", z == z_transpose, False, "chiral_inverse")
    recorder.check("nonsymmetric Z left inverse", rmul(z, z_inverse), rid(2), "chiral_inverse")
    recorder.check("nonsymmetric Z right inverse", rmul(z_inverse, z), rid(2), "chiral_inverse")
    for signature, op in operators.items():
        kappa = ONE if signature == "L" else MINUS_ONE
        h12 = matrix_scale(
            kappa * q(Fraction(-1, 4)),
            tensor_r_poly(z_transpose, op.bar_d2),
        )
        h21 = matrix_scale(
            kappa * q(Fraction(-1, 4)),
            tensor_r_poly(z, op.d2),
        )
        g12_numerator = matrix_scale(
            -kappa * q(Fraction(1, 4)),
            tensor_r_poly(z_inverse, op.bar_d2),
        )
        g21_numerator = matrix_scale(
            -kappa * q(Fraction(1, 4)),
            tensor_r_poly(z_inverse_transpose, op.d2),
        )
        expected_plus = matrix_scale(
            q(Fraction(1, 16)),
            tensor_r_poly(rid(2), op.n_plus),
        )
        expected_minus = matrix_scale(
            q(Fraction(1, 16)),
            tensor_r_poly(rid(2), op.n_minus),
        )
        recorder.check(
            f"{signature} nonsymmetric Z H12 G21",
            matrix_multiply(h12, g21_numerator),
            expected_plus,
            "chiral_inverse",
        )
        recorder.check(
            f"{signature} nonsymmetric Z H21 G12",
            matrix_multiply(h21, g12_numerator),
            expected_minus,
            "chiral_inverse",
        )
        recorder.check(
            f"{signature} nonsymmetric Z G12 H21",
            matrix_multiply(g12_numerator, h21),
            expected_plus,
            "chiral_inverse",
        )
        recorder.check(
            f"{signature} nonsymmetric Z G21 H12",
            matrix_multiply(g21_numerator, h12),
            expected_minus,
            "chiral_inverse",
        )


