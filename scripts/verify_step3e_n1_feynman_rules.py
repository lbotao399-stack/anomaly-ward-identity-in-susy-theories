def levi_civita_3(a: int, b: int, c: int) -> int:
    if len({a, b, c}) < 3:
        return 0
    inversions = sum(1 for i, j in ((a, b), (a, c), (b, c)) if i > j)
    return -1 if inversions % 2 else 1


def brst_nilpotency_checks(recorder: Recorder) -> None:
    parity = {
        "c": 1,
        "ct": 1,
        "phi": 0,
        "E": 0,
        "u_even": 0,
        "v_odd": 1,
        "u_odd": 1,
        "v_even": 0,
    }

    def free_add(
        left: dict[tuple[str, ...], QI], right: dict[tuple[str, ...], QI]
    ) -> dict[tuple[str, ...], QI]:
        result = dict(left)
        for word, coefficient in right.items():
            result[word] = result.get(word, ZERO) + coefficient
            if result[word] == ZERO:
                del result[word]
        return result

    def free_scale(
        coefficient: QI, polynomial: dict[tuple[str, ...], QI]
    ) -> dict[tuple[str, ...], QI]:
        return {
            word: coefficient * value
            for word, value in polynomial.items()
            if coefficient * value != ZERO
        }

    def s_generator(symbol: str) -> dict[tuple[str, ...], QI]:
        if symbol == "c":
            return {("c", "c"): I}
        if symbol == "ct":
            return {("ct", "ct"): I}
        if symbol == "phi":
            return {("c", "phi"): I}
        if symbol == "E":
            return {("ct", "E"): I, ("E", "c"): MINUS_I}
        if symbol == "u_even":
            return {("v_odd",): ONE}
        if symbol == "u_odd":
            return {("v_even",): ONE}
        if symbol in {"v_odd", "v_even"}:
            return {}
        raise KeyError(symbol)

    def s_word(word: tuple[str, ...]) -> dict[tuple[str, ...], QI]:
        result: dict[tuple[str, ...], QI] = {}
        preceding_parity = 0
        for index, symbol in enumerate(word):
            sign = MINUS_ONE if preceding_parity % 2 else ONE
            replacement = free_scale(sign, s_generator(symbol))
            contribution = {
                word[:index] + middle + word[index + 1 :]: coefficient
                for middle, coefficient in replacement.items()
            }
            result = free_add(result, contribution)
            preceding_parity += parity[symbol]
        return result

    def s_free(
        polynomial: dict[tuple[str, ...], QI]
    ) -> dict[tuple[str, ...], QI]:
        result: dict[tuple[str, ...], QI] = {}
        for word, coefficient in polynomial.items():
            result = free_add(result, free_scale(coefficient, s_word(word)))
        return result

    for symbol in ("c", "ct", "phi", "E", "u_even", "v_odd", "u_odd", "v_even"):
        first = s_generator(symbol)
        recorder.check(
            f"BRST free-word nilpotency on {symbol}",
            s_free(first),
            {},
            "brst",
        )

    ghosts = [basis_vector(1 << index) for index in range(3)]
    s_ghost: list[list[QI]] = []
    for a in range(3):
        value = [ZERO for _ in range(DIM)]
        for b in range(3):
            for c in range(3):
                coefficient = q(Fraction(-levi_civita_3(a, b, c), 2))
                term = exterior_multiply(ghosts[b], ghosts[c])
                value = [
                    value[index] + coefficient * term[index] for index in range(DIM)
                ]
        s_ghost.append(value)
    s2_ghost: list[list[QI]] = []
    for a in range(3):
        value = [ZERO for _ in range(DIM)]
        for b in range(3):
            for c in range(3):
                coefficient = q(Fraction(-levi_civita_3(a, b, c), 2))
                first = exterior_multiply(s_ghost[b], ghosts[c])
                second = exterior_multiply(ghosts[b], s_ghost[c])
                value = [
                    value[index] + coefficient * (first[index] - second[index])
                    for index in range(DIM)
                ]
        s2_ghost.append(value)
    recorder.check(
        "BRST ghost nilpotency su2 exterior witness",
        s2_ghost,
        [[ZERO for _ in range(DIM)] for _ in range(3)],
        "brst",
    )
    jacobi = {
        (a, b, c, d): sum(
            levi_civita_3(a, b, e) * levi_civita_3(e, c, d)
            + levi_civita_3(b, c, e) * levi_civita_3(e, a, d)
            + levi_civita_3(c, a, e) * levi_civita_3(e, b, d)
            for e in range(3)
        )
        for a in range(3)
        for b in range(3)
        for c in range(3)
        for d in range(3)
    }
    recorder.check("BRST Jacobi residual", set(jacobi.values()), {0}, "brst")
    recorder.check("BRST matter nilpotency coefficient", I * I + ONE, ZERO, "brst")
    recorder.check(
        "BRST contractible-doublet nilpotency",
        {"s2u": 0, "s2v": 0},
        {"s2u": 0, "s2v": 0},
        "brst",
    )
    bridge_terms = {
        "tilde_c2_E": Fraction(-1) + Fraction(1),
        "tilde_c_E_c": Fraction(-1) + Fraction(1),
        "E_c2": Fraction(-1) + Fraction(1),
    }
    recorder.check(
        "BRST bridge nilpotency word coefficients",
        bridge_terms,
        {key: Fraction(0) for key in bridge_terms},
        "brst",
    )


