def linear_combination(coefficients: Iterable[tuple[QI | Poly, Matrix]]) -> Matrix:
    result = zero_matrix()
    for coefficient, matrix in coefficients:
        result = matrix_add(result, matrix_scale(coefficient, matrix))
    return result


