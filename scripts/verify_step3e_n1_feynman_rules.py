@dataclass
class SuperspaceOperators:
    signature: str
    d: tuple[Matrix, Matrix]
    bar_d: tuple[Matrix, Matrix]
    d_up: tuple[Matrix, Matrix]
    bar_d_up: tuple[Matrix, Matrix]
    d2: Matrix
    bar_d2: Matrix
    x_operator: Matrix
    box: Poly
    n_plus: Matrix
    n_minus: Matrix
    n_transverse: Matrix


def build_operators(signature: str) -> SuperspaceOperators:
    sigma = SIGMA_L if signature == "L" else SIGMA_E
    d_phase = MINUS_I if signature == "L" else ONE
    bar_phase = I if signature == "L" else MINUS_ONE
    d_lower = []
    bar_lower = []
    for a in range(2):
        d_term = linear_combination(
            (Poly.constant(d_phase * sigma[mu][a][dot]) * DVAR[mu], BAR_THETA_UP[dot])
            for mu in range(4)
            for dot in range(2)
        )
        d_lower.append(matrix_add(PARTIAL_THETA[a], d_term))
    for dot in range(2):
        bar_term = linear_combination(
            (Poly.constant(bar_phase * sigma[mu][a][dot]) * DVAR[mu], THETA[a])
            for mu in range(4)
            for a in range(2)
        )
        bar_lower.append(matrix_add(BAR_PARTIAL_DOWN[dot], bar_term))
    d = tuple(d_lower)
    bar_d = tuple(bar_lower)
    d_up = tuple(
        linear_combination((EPSILON_UP[a][b], d[b]) for b in range(2))
        for a in range(2)
    )
    bar_d_up = tuple(
        linear_combination((EPSILON_UP[a][b], bar_d[b]) for b in range(2))
        for a in range(2)
    )
    d2 = matrix_sum(matrix_multiply(d_up[a], d[a]) for a in range(2))
    bar_d2 = matrix_sum(matrix_multiply(bar_d[a], bar_d_up[a]) for a in range(2))
    x_operator = matrix_sum(
        matrix_multiply(matrix_multiply(d_up[a], bar_d2), d[a]) for a in range(2)
    )
    if signature == "L":
        box = DVAR[0] * DVAR[0].scale(MINUS_ONE)
        for index in range(1, 4):
            box = box + DVAR[index] * DVAR[index]
    else:
        box = psum(DVAR[index] * DVAR[index] for index in range(4))
    n_plus = matrix_multiply(bar_d2, d2)
    n_minus = matrix_multiply(d2, bar_d2)
    n_transverse = matrix_scale(q(-2), x_operator)
    return SuperspaceOperators(
        signature,
        d,
        bar_d,
        d_up,
        bar_d_up,
        d2,
        bar_d2,
        x_operator,
        box,
        n_plus,
        n_minus,
        n_transverse,
    )


def serialize(value: Any) -> Any:
    if isinstance(value, QI):
        return value.text()
    if isinstance(value, Fraction):
        return str(value)
    if isinstance(value, Poly):
        return [
            {"powers": list(power), "coefficient": coefficient.text()}
            for power, coefficient in value.terms
        ]
    if isinstance(value, tuple):
        return [serialize(item) for item in value]
    if isinstance(value, list):
        return [serialize(item) for item in value]
    if isinstance(value, set):
        return [serialize(item) for item in sorted(value, key=str)]
    if isinstance(value, dict):
        return {str(key): serialize(item) for key, item in value.items()}
    return value


def fingerprint(value: Any) -> str:
    payload = json.dumps(serialize(value), sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


class Recorder:
    def __init__(self) -> None:
        self.checks: list[dict[str, Any]] = []
        self.failures: list[dict[str, Any]] = []

    def check(self, name: str, actual: Any, expected: Any, category: str) -> None:
        passed = actual == expected
        row: dict[str, Any] = {
            "name": name,
            "category": category,
            "passed": passed,
            "actual_sha256": fingerprint(actual),
            "expected_sha256": fingerprint(expected),
        }
        if isinstance(actual, (str, int, bool)) or actual is None:
            row["actual"] = actual
            row["expected"] = expected
        self.checks.append(row)
        if not passed:
            self.failures.append(
                {
                    "name": name,
                    "category": category,
                    "actual": serialize(actual),
                    "expected": serialize(expected),
                }
            )


