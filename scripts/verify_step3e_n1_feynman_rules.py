def finite_regulator_gate_checks(recorder: Recorder) -> None:
    projector = rdiag((1, 1, 0))
    complement = rsub(rid(3), projector)
    d_closed = rdiag((2, 3, 5))
    bar_closed = rdiag((7, 11, 13))
    recorder.check(
        "finite gate D intertwiner",
        rmul(projector, d_closed),
        rmul(d_closed, projector),
        "finite_regulator",
    )
    recorder.check(
        "finite gate barD intertwiner",
        rmul(projector, bar_closed),
        rmul(bar_closed, projector),
        "finite_regulator",
    )

    def defect(d_matrix: RMatrix, bar_matrix: RMatrix) -> tuple[RMatrix, RMatrix]:
        d_nu = rmul(rmul(projector, d_matrix), projector)
        bar_nu = rmul(rmul(projector, bar_matrix), projector)
        compressed = radd(rmul(d_nu, bar_nu), rmul(bar_nu, d_nu))
        ambient = rmul(
            rmul(
                projector,
                radd(rmul(d_matrix, bar_matrix), rmul(bar_matrix, d_matrix)),
            ),
            projector,
        )
        left = rsub(compressed, ambient)
        right = rneg(
            radd(
                rmul(
                    rmul(rmul(rmul(projector, d_matrix), complement), bar_matrix),
                    projector,
                ),
                rmul(
                    rmul(rmul(rmul(projector, bar_matrix), complement), d_matrix),
                    projector,
                ),
            )
        )
        return left, right

    closed_left, closed_right = defect(d_closed, bar_closed)
    recorder.check(
        "finite gate defect formula on closed regulator",
        closed_left,
        closed_right,
        "finite_regulator",
    )
    recorder.check(
        "finite gate closed defect vanishes",
        closed_left,
        rzero(3, 3),
        "finite_regulator",
    )

    d_open = [
        [Fraction(0), Fraction(0), Fraction(1)],
        [Fraction(0), Fraction(0), Fraction(0)],
        [Fraction(1), Fraction(0), Fraction(0)],
    ]
    bar_open = [row[:] for row in d_open]
    open_left, open_right = defect(d_open, bar_open)
    recorder.check(
        "finite gate leakage defect identity",
        open_left,
        open_right,
        "finite_regulator",
    )
    recorder.check(
        "finite gate leakage defect retained nonzero",
        open_left != rzero(3, 3),
        True,
        "finite_regulator",
    )
    box_residual = rdiag((2, 3))
    box_inverse = rdiag((Fraction(1, 2), Fraction(1, 3)))
    recorder.check(
        "finite gate Box inverse left",
        rmul(box_residual, box_inverse),
        rid(2),
        "finite_regulator",
    )
    recorder.check(
        "finite gate Box inverse right",
        rmul(box_inverse, box_residual),
        rid(2),
        "finite_regulator",
    )


