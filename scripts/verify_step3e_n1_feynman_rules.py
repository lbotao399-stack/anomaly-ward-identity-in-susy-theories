def qmatrix_vector(matrix: QMatrix, vector: list[QI]) -> list[QI]:
    return [
        sum_qi(matrix[row][column] * vector[column] for column in range(len(vector)))
        for row in range(len(matrix))
    ]


def sum_qi(values: Iterable[QI]) -> QI:
    result = ZERO
    for value in values:
        result = result + value
    return result


def evaluate_matrix(matrix: Matrix, values: tuple[QI, QI, QI, QI]) -> QMatrix:
    return [[entry.evaluate(values) for entry in row] for row in matrix]


def exterior_multiply(left: list[QI], right: list[QI]) -> list[QI]:
    result = [ZERO for _ in range(DIM)]
    for left_mask, left_value in enumerate(left):
        if left_value == ZERO:
            continue
        for right_mask, right_value in enumerate(right):
            if right_value == ZERO or left_mask & right_mask:
                continue
            inversions = 0
            for left_index in range(4):
                if left_mask & (1 << left_index):
                    inversions += sum(
                        1 for right_index in range(left_index) if right_mask & (1 << right_index)
                    )
            sign = MINUS_ONE if inversions % 2 else ONE
            result[left_mask | right_mask] = (
                result[left_mask | right_mask] + sign * left_value * right_value
            )
    return result


def basis_vector(mask: int, value: QI = ONE) -> list[QI]:
    result = [ZERO for _ in range(DIM)]
    result[mask] = value
    return result


def qmatrix_linear_combination(terms: Iterable[tuple[QI, QMatrix]]) -> QMatrix:
    result = [[ZERO for _ in range(DIM)] for _ in range(DIM)]
    for coefficient, matrix in terms:
        for row in range(DIM):
            for column in range(DIM):
                result[row][column] = result[row][column] + coefficient * matrix[row][column]
    return result


def wz_vector(signature: str, gauge_vector: tuple[QI, QI, QI, QI]) -> list[QI]:
    sigma = SIGMA_L if signature == "L" else SIGMA_E
    coefficient = q(-2) if signature == "L" else q(-2) * I
    theta_vectors = (basis_vector(1), basis_vector(2))
    bar_upper_vectors = (basis_vector(8), basis_vector(4, MINUS_ONE))
    result = [ZERO for _ in range(DIM)]
    for mu in range(4):
        for a in range(2):
            for dot in range(2):
                term = exterior_multiply(theta_vectors[a], bar_upper_vectors[dot])
                factor = coefficient * gauge_vector[mu] * sigma[mu][a][dot]
                result = [result[index] + factor * term[index] for index in range(DIM)]
    return result


